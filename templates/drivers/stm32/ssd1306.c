/* ===== 软件 I2C 底层 ===== */
static void i2c_delay(void) { for (volatile int i = 0; i < 8; i++) __NOP(); }
static void scl_low(SSD1306_HandleTypeDef *h)  { HAL_GPIO_WritePin(h->scl_port, h->scl_pin, GPIO_PIN_RESET); }
static void scl_high(SSD1306_HandleTypeDef *h) { HAL_GPIO_WritePin(h->scl_port, h->scl_pin, GPIO_PIN_SET); }
static void sda_low(SSD1306_HandleTypeDef *h)  { HAL_GPIO_WritePin(h->sda_port, h->sda_pin, GPIO_PIN_RESET); }
static void sda_high(SSD1306_HandleTypeDef *h) { HAL_GPIO_WritePin(h->sda_port, h->sda_pin, GPIO_PIN_SET); }

static void i2c_start(SSD1306_HandleTypeDef *h) {
  sda_high(h); scl_high(h); i2c_delay();
  sda_low(h);  i2c_delay();
  scl_low(h);  i2c_delay();
}
static void i2c_stop(SSD1306_HandleTypeDef *h) {
  sda_low(h);  i2c_delay();
  scl_high(h); i2c_delay();
  sda_high(h); i2c_delay();
}
static void i2c_write_byte(SSD1306_HandleTypeDef *h, uint8_t b) {
  for (int i = 0; i < 8; i++) {
    if (b & 0x80) sda_high(h); else sda_low(h);
    b <<= 1;
    i2c_delay();
    scl_high(h); i2c_delay();
    scl_low(h);  i2c_delay();
  }
  scl_high(h); i2c_delay(); scl_low(h); /* ACK 忽略 */
}
static void write_cmd(SSD1306_HandleTypeDef *h, uint8_t cmd) {
  i2c_start(h);
  i2c_write_byte(h, 0x78); /* 从机地址 + 写 */
  i2c_write_byte(h, 0x00); /* 控制字节：命令 */
  i2c_write_byte(h, cmd);
  i2c_stop(h);
}
static void write_data(SSD1306_HandleTypeDef *h, uint8_t *data, uint16_t len) {
  i2c_start(h);
  i2c_write_byte(h, 0x78);
  i2c_write_byte(h, 0x40); /* 控制字节：数据 */
  for (uint16_t i = 0; i < len; i++) i2c_write_byte(h, data[i]);
  i2c_stop(h);
}


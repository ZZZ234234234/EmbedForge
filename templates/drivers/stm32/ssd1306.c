void SSD1306_Init(SSD1306_HandleTypeDef *h,
                  GPIO_TypeDef *scl_port, uint16_t scl_pin,
                  GPIO_TypeDef *sda_port, uint16_t sda_pin) {
  h->scl_port = scl_port; h->scl_pin = scl_pin;
  h->sda_port = sda_port; h->sda_pin = sda_pin;
  h->cur_x = 0; h->cur_y = 0;

  GPIO_InitTypeDef g = {0};
  g.Mode = GPIO_MODE_OUTPUT_OD;
  g.Speed = GPIO_SPEED_FREQ_HIGH;
  g.Pin = scl_pin; HAL_GPIO_Init(scl_port, &g);
  g.Pin = sda_pin; HAL_GPIO_Init(sda_port, &g);

  HAL_Delay(100);
  write_cmd(h, 0xAE); /* display off */
  write_cmd(h, 0x20); write_cmd(h, 0x00); /* horizontal addressing */
  write_cmd(h, 0xB0); /* page 0 */
  write_cmd(h, 0xC8); /* com scan dir */
  write_cmd(h, 0x00); write_cmd(h, 0x10); /* column addr */
  write_cmd(h, 0x40); /* start line */
  write_cmd(h, 0x81); write_cmd(h, 0x7F); /* contrast */
  write_cmd(h, 0xA1); /* segment remap */
  write_cmd(h, 0xA6); /* normal display */
  write_cmd(h, 0xA8); write_cmd(h, 0x3F); /* multiplex 1/64 */
  write_cmd(h, 0xA4); /* output follows RAM */
  write_cmd(h, 0xD3); write_cmd(h, 0x00); /* display offset */
  write_cmd(h, 0xD5); write_cmd(h, 0xF0); /* clock divide */
  write_cmd(h, 0xD9); write_cmd(h, 0x22); /* pre-charge */
  write_cmd(h, 0xDA); write_cmd(h, 0x12); /* com pins */
  write_cmd(h, 0xDB); write_cmd(h, 0x20); /* vcom detect */
  write_cmd(h, 0x8D); write_cmd(h, 0x14); /* charge pump */
  write_cmd(h, 0xAF); /* display on */

  SSD1306_Clear(h);
  SSD1306_Update(h);
}

void SSD1306_Clear(SSD1306_HandleTypeDef *h) {
  for (uint32_t i = 0; i < sizeof(h->buf); i++) h->buf[i] = 0;
  h->cur_x = 0; h->cur_y = 0;
}

void SSD1306_SetCursor(SSD1306_HandleTypeDef *h, uint8_t col, uint8_t page) {
  h->cur_x = col; h->cur_y = page;
}

void SSD1306_Putc(SSD1306_HandleTypeDef *h, char c) {
  if (c < 32 || c > 90) c = 32;
  const uint8_t *glyph = font6x8[c - 32];
  for (int i = 0; i < 6; i++) {
    uint16_t idx = (h->cur_y * SSD1306_WIDTH) + h->cur_x;
    if (idx < sizeof(h->buf)) h->buf[idx] = glyph[i];
    h->cur_x++;
    if (h->cur_x >= SSD1306_WIDTH) { h->cur_x = 0; h->cur_y++; }
    if (h->cur_y >= SSD1306_HEIGHT / 8) { h->cur_y = 0; }
  }
}

void SSD1306_Puts(SSD1306_HandleTypeDef *h, const char *s) {
  while (*s) SSD1306_Putc(h, *s++);
}

void SSD1306_Update(SSD1306_HandleTypeDef *h) {
  for (uint8_t page = 0; page < 8; page++) {
    write_cmd(h, 0xB0 + page);
    write_cmd(h, 0x00);
    write_cmd(h, 0x10);
    write_data(h, &h->buf[page * SSD1306_WIDTH], SSD1306_WIDTH);
  }
}
